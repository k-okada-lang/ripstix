<h2 id="where">「千葉南」とはどこ？</h2>
<p>千葉県のサーフエリアは、大きく「千葉北」と「千葉南」に分けて呼ばれます。九十九里浜沿いのエリアが千葉北、<strong>勝浦から南房総にかけてのエリアが千葉南</strong>です。波情報サイトや天気予報でも、この呼び分けがよく使われます。</p>
<p>千葉南には、北から順に、御宿・勝浦、鴨川、和田、千倉、そして半島の先をまわった館山・平砂浦などのエリアがあります。</p>

