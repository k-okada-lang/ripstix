<p>千葉北は「どこに行っても似た条件の波がある」のに対して、千葉南は<strong>「場所ごとに条件が違うので、その日に合う場所を選ぶ楽しさがある」</strong>エリアだといえます。海岸の向きがばらばらなぶん、風向きが変わっても、どこかにオフショアのポイントが見つかりやすいのが強みです。</p>

<h2 id="areas">エリア別：千葉南の主なポイント</h2>
<h3>御宿・勝浦エリア</h3>
<p>千葉南の北の入り口です。御宿は白い砂浜が広がるビーチで、御宿の岩和田のように初心者にもすすめやすいポイントがあります。一方、勝浦の部原（へばら）は、パワーのある波が割れる上級者向けのポイントとして知られています。同じエリアでもレベルの差が大きいので、ポイント選びは慎重に。</p>
<h3>鴨川エリア</h3>
<p>鴨川の市街地に面した海岸には、マルキをはじめ、たくさんのポイントが並びます。ショップやスクール、宿も多く、千葉南の中でもサーフィンの拠点にしやすい街です。北〜北西の風でオフショアになるポイントが多くあります。</p>
<h3>和田エリア</h3>
<p>南房総市和田町には、白渚、J's前、花籠、千歳など、小さな岬や岩場に区切られたポイントが続きます。形の良い波が割れるポイントが集まり、北・西・北西の風でオフショアになります。わたしたち SPLASH があるのも、このエリアの<a href="../../column/shirasuka-surf-guide/">白渚</a>です。</p>
<h3>千倉エリア</h3>
<p>なだらかなビーチが中心で、初心者から楽しめるエリアです。西〜北西の風がオフショアです。</p>
<h3>館山・平砂浦エリア</h3>
<p>房総半島の先をまわった、南〜南西向きの長い砂浜です。北・北東・東の風がオフショアになるため、外房側が北東の風で荒れている日の「逃げ場」として頼りになります。</p>
