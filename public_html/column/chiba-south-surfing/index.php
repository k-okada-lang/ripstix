<tr><td>海岸</td><td>まっすぐな長い砂浜が続く</td><td>岬や入り江が多く、入り組んだ海岸</td></tr>
<tr><td>波のタイプ</td><td>ビーチブレイクが中心</td><td>ビーチに加え、リーフや岩場のポイントも多い</td></tr>
<tr><td>海岸の向き</td><td>ほぼ東向きにそろう</td><td>東・南東・南・南西と場所によってさまざま</td></tr>
