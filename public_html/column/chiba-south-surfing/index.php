<li><b>うねり</b>：千葉南の外房側は、東〜南のうねりに広く反応します。夏〜秋は南の海上の台風から、冬は低気圧の通過でうねりが届きます。</li>
<li><b>冬の北西風</b>：冬は北西の季節風が吹く日が多く、外房側の多くのポイントがオフショアになります。千葉南の冬が「波の質が良い季節」といわれる理由のひとつです。</li>
<li><b>台風のうねり</b>：サイズが急に上がり、流れも強くなります。経験に合わないサイズの日は、見るだけにする勇気も大切です。</li>
</ul>

