<h2 id="why">南房総でサーフィンをする魅力</h2>
<p>南房総（南房総市と館山市のあたり）は、太平洋に突き出た房総半島の先端部分です。サーフィンをするうえでの魅力は、大きく3つあります。</p>
<ul>
<li><b>冬でも比較的あたたかい</b>：黒潮の影響を受けやすく、真冬でも陸の気温・水温ともに関東のほかのエリアよりおだやかな日が多いのが特徴です。</li>
<li><b>海岸の向きがいろいろ</b>：東を向いた外房側の海岸と、南〜南西を向いた館山側の海岸があるため、風向きが変わっても「今日はこっちがオフショア（陸から海へ吹く、波の形が整う風）」という場所を探しやすいエリアです。</li>
<li><b>ポイントの種類が幅広い</b>：遠浅のビーチブレイクから、岩やリーフの上で割れる形の良いポイントまでそろっています。初心者から上級者まで、レベルに合った場所を選べます。</li>
</ul>
<p>都心から車で行ける距離にありながら、九十九里や一宮の周辺に比べるとのんびりした雰囲気が残っているのも、南房総ならではの良さです。</p>

<h2 id="area">エリアと主なポイント</h2>
<p>南房総のサーフポイントは、おおまかに「和田エリア」「千倉エリア」「館山（平砂浦）エリア」に分けて考えるとわかりやすくなります。北どなりには鴨川エリアがあります。</p>
<table class="tbl"><thead><tr><th>エリア</th><th>主なポイント</th><th>オフショアの目安</th><th>ひとこと</th></tr></thead><tbody>
<tr><td>和田</td><td>白渚、J's前、花籠、千歳 など</td><td>北・西・北西</td><td>東〜南のうねりに反応。形の良いポイントが集まる</td></tr>
<tr><td>千倉</td><td>千倉 など</td><td>西・北西</td><td>初心者にもすすめやすいビーチが中心</td></tr>
<tr><td>館山（平砂浦）</td><td>平砂浦 など</td><td>北・北東・東</td><td>南〜南西を向いた長いビーチ。北東風の日の候補</td></tr>
</tbody></table>
<p class="note">※ オフショアの風向きは、サーフィン情報サイト「SURF LIFE」の南房総エリアのポイント情報を目安にしています。実際の波は地形や潮の満ち引きで変わります。</p>

<h3>和田エリア（白渚・J's前・花籠・千歳）</h3>
<p>南房総市和田町の海岸には、小さな岬や岩場に区切られたポイントが続きます。そのひとつが、わたしたちのショップの目の前にある<a href="../../column/shirasuka-surf-guide/">白渚（しらすか）</a>です。砂の下にリーフや岩がある場所が多く、サイズが上がっても波の形が崩れにくいのが特徴です。そのぶん、岩の位置や出入りの場所を知っておくことが大切です。</p>

<h3>千倉エリア</h3>
<p>千倉は、なだらかなビーチで割れる波が中心で、サーフィン情報サイトでも初心者向けとして紹介されることの多いエリアです。西〜北西の風でオフショアになります。南房総ではじめて海に入るなら、まず候補に入れたい場所です。</p>

<h3>館山・平砂浦エリア</h3>
<p>平砂浦は、館山市の南側に長く続く砂浜です。外房側とは海岸の向きが違い、北〜北東〜東の風がオフショアになります。外房側が北東の風で崩れている日に、波が整っていることがあるのが心強いところです。砂が動きやすく、割れる場所（ブレイク）が変わりやすいので、海に入る前にしっかり波を見ましょう。</p>

<h2 id="wind">風向きで選ぶ：その日の正解の見つけ方</h2>
<p>南房総で良い波に当たるコツは、<strong>「うねりの向き」と「風向き」をセットで見る</strong>ことです。</p>
<ol class="steps">
<li><b>うねりが入っているか</b>：外房側のポイントは東〜南のうねり、平砂浦は南〜南西のうねりに反応しやすい傾向があります。台風や低気圧が南の海上にあるときは、南房総全体に波が届きやすくなります。</li>
<li><b>風向きを確認する</b>：北西〜西の風なら和田・千倉など外房側、北東〜東の風なら平砂浦が候補です。</li>
<li><b>潮回りを見る</b>：リーフやボトムが浅いポイントは、潮が引きすぎると危ないことがあります。満潮・干潮の時刻もチェックしましょう。</li>
<li><b>最後は自分の目で</b>：予報はあくまで目安です。現地で10分ほど波を見て、セットの大きさ、人の数、カレント（流れ）を確かめてから入りましょう。</li>
</ol>
<p class="note">冬は北西の季節風が吹く日が多く、外房側のポイントがオフショアになりやすい季節です。南からの風が強い日は、南房総のどこも波が乱れやすくなります。</p>

<h2 id="season">季節ごとの波とウェットスーツの目安</h2>
<table class="tbl"><thead><tr><th>季節</th><th>波の傾向</th><th>ウェットスーツの目安</th></tr></thead><tbody>
<tr><td>春（3〜5月）</td><td>低気圧の通過で波が上がる日がある。風が変わりやすい</td><td>3〜4月はセミドライ、5月は3mm前後のフルスーツ</td></tr>
<tr><td>夏（6〜8月）</td><td>小さめの日が多いが、南の台風からうねりが届くことも。人が増える</td><td>3/2mmのフルスーツ〜スプリング、真夏はタッパーやラッシュガード</td></tr>
<tr><td>秋（9〜11月）</td><td>台風のうねりで、いちばん波に当たりやすい時期</td><td>9月はスプリング、10〜11月は3/2mmのフルスーツ</td></tr>
<tr><td>冬（12〜2月）</td><td>北西の風でオフショアになりやすく、人も少なめ</td><td>5/3mmのセミドライ。ブーツやグローブがあると快適</td></tr>
</tbody></table>
<p class="note">※ ウェットスーツは、その年の水温や体感で選んでください。寒さに弱い方は、ひとつ暖かい仕様を選ぶと安心です。台風のうねりはサイズが急に上がることがあるので、無理は禁物です。</p>

<h2 id="beginner">はじめて・初心者が南房総で入るなら</h2>
<ul>
<li><b>ビーチブレイクを選ぶ</b>：最初は、千倉や平砂浦のような砂のビーチがおすすめです。リーフや岩場のポイントは、慣れてからにしましょう。</li>
<li><b>スクールやショップを頼る</b>：その日の波に合う場所や、ポイントのルールを教えてもらえます。南房総にはサーフスクールを開いているショップもあります。</li>
<li><b>ひとりで入らない</b>：はじめての場所では、必ず誰かと一緒に。離岸流（沖へ向かう強い流れ）に流されたら、岸と平行に泳いで流れから抜けます。</li>
<li><b>ローカルルールとマナー</b>：ピーク（波が最初に割れる場所）に近い人が優先です。前乗りをしない、駐車場やゴミのマナーを守るなど、地域の人へのあいさつと思いやりを大切にしてください。</li>
</ul>
<p>ボードの選び方に迷ったら、<a href="../../column/how-to-choose-surfboard/">サーフボードの選び方（サイズとボリューム）</a>もあわせてどうぞ。</p>

<h2 id="access">アクセスと一日の過ごし方</h2>
<ul>
<li><b>車</b>：東京湾アクアラインから館山自動車道・富津館山道路へ。和田方面は「富浦IC」から国道128号などで約20分です。都心からの所要時間は、交通状況によりますがおおよそ2時間前後が目安です。</li>
<li><b>電車</b>：JR内房線（館山・千倉・和田浦などの駅）を利用できます。ボードを持っての移動は、駅からの距離も確認しておきましょう。</li>
<li><b>駐車場</b>：ポイント近くの駐車場は、季節や場所で料金やルールが異なります。路上駐車や私有地への駐車は絶対にやめましょう。</li>
</ul>
<p>朝いちばんで波に乗り、昼は海沿いで地元の魚料理を味わって、夕方にもう一度、という一日の過ごし方ができるのも南房総の楽しみです。白渚にお越しの際は、SPLASH にも気軽に立ち寄ってください。波の様子をお伝えします。</p>

