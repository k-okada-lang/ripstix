<p>お店の目の前がポイントなので、削ったボードをすぐに海で試し、乗った感触を次の一本に生かせます。白渚をはじめとした南房総の波を知り尽くしていることが、吉田のボードづくりの土台です。</p>

<h2 id="brand">R.I.P surfboard から RIPSTIX へ</h2>
<p>吉田は以前、<b>R.I.P surfboard</b> の名前でボードを削っていました。そのボードづくりを引き継いでいるのが、いまのブランド <a href="../../column/ripstix-surfboard/">RIPSTIX（リップスティックス）</a>です。ブランドの名前は変わりましたが、削る人も、削る場所も同じです。</p>
<p>R.I.P のボードに乗っていた方から、「同じような形で、いまの自分に合わせた一本がほしい」と相談を受けることもあります。手元のボードを持ってきていただければ、寸法や形を確かめたうえで、いまの乗り方に合わせて形を見直します。</p>

<h2 id="shape">ボードづくりで大切にしていること</h2>
<h3>乗る人と、行く波を聞いてから削る</h3>
<p>カスタムボードは、同じ「6フィートのショートボード」でも、乗る人の体重やレベル、よく行く波によって、合う浮力や形が変わります。吉田はオーダーのとき、身長・体重、サーフィン歴、よく行くポイント、いま乗っているボードと、その乗り心地をくわしく聞きます。数字だけでなく、「パドルがきつい」「ターンで引っかかる」といった感覚を聞くことで、次の一本で何を変えればいいかが見えてきます。</p>
<h3>決まっていなくても、おまかせでいい</h3>
<p>「何を決めればいいのか分からない」という方も少なくありません。RIPSTIX では、細かいことが決まっていなくても大丈夫です。話を聞いたうえで、サイズ、テール、レール、フィン、カラーを一緒に詰めていきます。「おまかせ」で頼むこともできます。</p>
<h3>乗り方が変われば、ボードも変える</h3>
<p>ミッドレングスでオーダーしたお客さんが、上達して攻めるサーフィンがしたくなり、ショートボードでオーダーし直すこともあります。サーフィンが変われば、合うボードも変わります。いまの自分に合う一本を、その都度一緒に考えるのが、近くにシェイパーがいる良さです。シェイパーに頼むことと既製品の違いは、<a href="../../column/shaper-vs-stock/">カスタムボードと既製品（ストック）の違い</a>でくわしく説明しています。</p>
<h3>一本ずつの手仕事だから、同じボードはない</h3>
<p>カラーは一本ずつ手作業で入れるため、同じ柄は二度とできません。気温・湿度・塗りの回数・クロスの質でも仕上がりが変わります。それも含めて「世界に一つだけ」のボードです。デザインの決め方は<a href="../../column/one-of-a-kind-surfboard/">世界に一つだけのサーフボードのつくり方</a>をどうぞ。</p>

<h2 id="repair">直すのも、シェイパーの仕事</h2>
<p>吉田は、削るだけでなく、ボードの修理も自分で手がけています。ボードの中がどうなっているかを知っているからこそ、傷の場所や大きさを見て、水抜き・乾燥からガラスの巻き直し、仕上げの磨きまで、状態に合った直し方を選べます。</p>
<p>小さな凹みから、二つに折れたボードまで対応しています。RIPSTIX や R.I.P 以外のブランドのボードも受け付けています。傷に気づいたら、早めに相談してください。水が入ったまま乗り続けると、中のフォームが傷んで修理が大きくなります。くわしくは<a href="../../column/surfboard-repair/">サーフボード修理ガイド</a>へ。</p>

