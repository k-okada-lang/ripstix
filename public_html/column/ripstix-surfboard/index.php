<h2 id="custom">カスタムで選べること</h2>
<ol class="steps">
<li><b>サイズ</b>：長さ・幅・厚み。体重とレベルから必要な浮力を考えます。</li>
<li><b>テール</b>：スカッシュ、ラウンド、ラウンドピン、スワローなど。<a href="../../column/surfboard-tail-types/">テールの種類と乗り味</a>で詳しく説明しています。</li>
<li><b>フィン</b>：トライ、クアッド、5フィンなど。<a href="../../column/surfboard-fin-setup/">フィンの種類とセッティング</a>もどうぞ。</li>
<li><b>カラー</b>：色は自由に選べます。<a href="../../column/one-of-a-kind-surfboard/">世界に一つだけのサーフボードのつくり方</a>で、カラーの入れ方を紹介しています。</li>
<li><b>ロゴ</b>：デッキ（上の面）とボトム（裏の面）で、位置を選べます。</li>
</ol>
<p>サイトの「ボードをつくる」画面では、これらを3Dで組み立てて、オーダーシートとしてまとめられます。決めた内容をそのまま店に持ってきていただくと、相談がスムーズです。細かいことが決まっていなくても、「おまかせ」で頼むこともできます。</p>
<p class="note">※ フィンとストリンガーの色は、製造工程の都合でご希望どおりにできない場合があります。カラーの仕上がりは気温・湿度・塗りの回数・クロスの質で変わるため、画面とまったく同じにはなりません。</p>

