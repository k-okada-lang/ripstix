<h2 id="about">RIPSTIX はどんなブランドか</h2>
<p>RIPSTIX は、白渚ポイントの目の前で営業するサーフショップ <?php if (rx_live('2026-12-04')): ?><a href="../../column/splash-shirasuka/">SPLASH（スプラッシュ）</a><?php else: ?>SPLASH（スプラッシュ）<?php endif; ?>のオリジナルブランドです。シェイパーの<?php if (rx_live('2026-12-05')): ?><a href="../../column/shaper-yoshida-masayuki/">吉田正幸</a><?php else: ?>吉田正幸<?php endif; ?>が、お客さん一人ひとりの体格やレベル、よく行く波を聞いてから、一本ずつ削っています。</p>
<p>ブランドの特徴は、次の3つです。</p>
<ul>
<li><b>世界に一つだけのカスタムボード</b>：サイズ、テール、フィン、カラー、ロゴの位置まで、乗る人に合わせて決めます。カラーは手作業で入れるため、同じ柄は二度とできません。</li>
<li><b>白渚の波で確かめながら削る</b>：工房の目の前が白渚ポイントです。削ったボードはすぐに海で試せるので、南房総の波で走るかどうかを確かめながら形を詰めています。</li>
<li><b>削る人が、直す人でもある</b>：凹みや割れ、折れなどの修理も、同じ店で受け付けています。ボードのつくりを知っているシェイパーが状態を見て直します。</li>
</ul>
<p>運営は株式会社LTR（代表取締役 吉田正幸）です。ショップの所在地は千葉県南房総市和田町白渚586-2です。</p>

<h2 id="rip">前身は R.I.P surfboard</h2>
<p>RIPSTIX の前身は、吉田正幸がボードを削っていた <b>R.I.P surfboard（R.I.P. surfboards）</b>です。いま RIPSTIX として削っているボードも、同じシェイパーが同じ白渚の工房で削っています。</p>
<p>「R.I.P のボードに乗っていた」「昔の R.I.P と同じような形がほしい」という方も、気軽にご相談ください。手元にあるボードを持ってきていただければ、寸法や形を確かめたうえで、いまの乗り方に合わせた一本を一緒に考えます。古い R.I.P のボードの修理も受け付けています。</p>
<p class="note">※ 表記は「RIPSTIX」が正式です。検索では「RIP STIX」「リップスティックス」「リップスティック」と書かれることもあります。</p>

