<h2 id="what">カスタムサーフボードとは</h2>
<p>カスタムサーフボードは、乗る人の体格・レベル・よく行く波・乗りたいスタイルに合わせて、シェイパーが一本ずつ削るオーダーメイドのボードです。既製品（ストックボード）が「多くの人に合うように作られた平均的な一本」だとすれば、カスタムは「あなた一人に合わせた一本」。長さや幅、厚み、ボリューム、テールやレールの形、ロッカー（反り）、フィンの配置、カラーやロゴまで決められます。</p>
<p>「上級者だけのもの」と思われがちですが、実は<strong>初心者や中級者ほどカスタムの恩恵は大きい</strong>と言えます。体重に対して浮力が足りないボードや、波に合っていないボードで練習を続けるより、自分に合った一本の方が上達が早いからです。</p>

<h2 id="flow">オーダーの流れ（相談から受け取りまで）</h2>
<ol class="steps">
<li><b>相談する</b>：お店で直接、または Instagram の DM で。今使っているボード、身長・体重、サーフィン歴、よく行くポイントを伝えます。</li>
<li><b>仕様を決める</b>：シェイパーと一緒に、タイプ、サイズ、ボリューム、テール、フィン、カラーを決めます。</li>
<li><b>シェイプ・ラミネート</b>：ブランクス（ボードの芯になるフォーム）を削り、ガラスクロスと樹脂で巻き、仕上げます。</li>
<li><b>受け取り</b>：完成したら受け取り。気になる点はその場でシェイパーに確認できます。</li>
</ol>
<p>製作期間は、時期や仕様、カラーの有無によって変わります。シーズン前は混み合うことが多いので、乗りたい時期から逆算して早めに相談するのがおすすめです。</p>

<h2 id="tell">シェイパーに伝えるべき6つのこと</h2>
<p>シェイパーは「あなたの情報」からボードを設計します。次の6つを伝えると、イメージに近い一本になりやすくなります。</p>
<table class="tbl">
<tr><th>伝えること</th><th>なぜ必要か</th></tr>
<tr><td>身長・体重</td><td>ボリューム（浮力）と長さを決める基本になります。ウェットスーツ込みで考えます。</td></tr>
<tr><td>サーフィン歴・レベル</td><td>テイクオフの速さや、求める安定感・操作性が変わります。</td></tr>
<tr><td>よく行くポイントと波のサイズ</td><td>腰〜胸の波が多いのか、頭以上も乗るのかで、ロッカーやテールが変わります。</td></tr>
<tr><td>今のボード（サイズとリッター）</td><td>「今の板より少し浮力が欲しい」など、比べる基準になります。</td></tr>
<tr><td>乗りたいスタイル</td><td>大きなターン、アップスンダウン、ノーズライディングなど、目指す乗り方を伝えます。</td></tr>
<tr><td>見た目の希望</td><td>カラー、ロゴの位置、ピンライン。写真や画像があると伝わりやすいです。</td></tr>
</table>
<p>RIPSTIX のサイトでは、<a href="../../#builder">ボードのカスタム画面</a>でタイプ・サイズ・カラー・ロゴ位置を組み、オーダーシートとして保存できます。相談のときにそのまま見せれば、話が早く進みます。</p>

<h2 id="fail">よくある失敗と、その避け方</h2>
<h3>「上級者の板」をそのままコピーしてしまう</h3>
<p>プロやうまい友人と同じサイズにすると、浮力が足りずにパドルやテイクオフで苦労しがちです。憧れのモデルは参考にしつつ、ボリュームは自分の体重とレベルで決めましょう。詳しくは<a href="../../column/how-to-choose-surfboard/">サーフボードの選び方（サイズとボリューム）</a>で解説しています。</p>
<h3>「全部入り」にしてしまう</h3>
<p>速さも、安定も、小回りも、すべてを一本で求めると、どれも中途半端になります。「この一本で一番やりたいこと」を一つ決めるのがコツです。</p>
<h3>カラーの仕上がりを完全に再現しようとする</h3>
<p>樹脂に色を入れるティントやレジンワークは、気温・湿度・塗りの回数・クロスの質で色味が変わる手仕事です。画面で見た色と完全に同じにはなりません。だからこそ、一本ずつ表情が違う「世界に一つだけ」のボードになります。デザインの決め方は<a href="../../column/one-of-a-kind-surfboard/">世界に一つだけのサーフボードのつくり方</a>へ。</p>

<h2 id="cost">価格の考え方</h2>
<p>カスタムの価格は、モデル（長さ）、素材（PU か EPS か）、カラーの手法、ロゴやピンラインなどのオプションで変わります。「予算はこれくらい」と最初に伝えておくと、その範囲でできる最善の仕様を提案してもらえます。RIPSTIX の価格と納期は、仕様をうかがったうえでご案内しています。</p>


<h2 id="design">形を決める主な要素（用語ミニ辞典）</h2>
<dl class="glossary">
<dt>アウトライン</dt><dd>上から見たボードの輪郭。幅の広い位置や、ノーズ・テールの幅で、安定感と小回りのバランスが決まります。</dd>
<dt>ロッカー</dt><dd>横から見たボードの反り。反りが少ないと速く、強いと掘れた波でも刺さりにくく、ターンで小回りが利きます。</dd>
<dt>レール</dt><dd>ボードのふち。厚く丸いレールは安定と浮力、薄く角のあるレールは水をつかむキレのある動きになります。</dd>
<dt>ボトム</dt><dd>裏面の形。フラット、シングルコンケーブ、ダブルコンケーブ、Vボトムなどがあり、水の流れ方とターンの感触が変わります。</dd>
<dt>ボリューム</dt><dd>ボードの体積（L）。浮力の目安で、パドルとテイクオフのしやすさに直結します。</dd>
<dt>ブランクス</dt><dd>ボードの芯になるフォーム材。PU（ポリウレタン）と EPS（発泡スチロール系）が代表的です。</dd>
</dl>
<p>すべてを自分で決める必要はありません。「こう乗りたい」を伝えれば、シェイパーがこれらを組み合わせて形にします。素材の違いは<a href="../../column/pu-vs-eps/">PU と EPS の違い</a>で詳しく解説しています。</p>

<h2 id="second">2本目以降こそカスタムが面白い</h2>
<p>1本目のカスタムに乗ると、「もう少しテールを細く」「次は少し短く」と、自分の好みがはっきりしてきます。その感想をシェイパーに伝えて2本目を削ると、ボードはぐっとあなたに近づきます。白渚の目の前で削る RIPSTIX なら、乗った翌日にそのまま感想を伝えに来ることもできます。</p>
