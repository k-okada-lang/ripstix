<h2 id="what">PU と EPS とは</h2>
<p><strong>PU（ポリウレタン）</strong>は、昔から使われている定番のフォームで、ポリエステル樹脂と組み合わせて仕上げます。<strong>EPS（発泡ポリスチレン）</strong>は軽く浮力のあるフォームで、エポキシ樹脂と組み合わせるのが一般的です。そのため EPS のボードは「エポキシボード」と呼ばれることもあります。</p>

<h2 id="compare">違いを比べる</h2>
<table class="tbl">
<tr><th></th><th>PU（ポリウレタン）</th><th>EPS（エポキシ）</th></tr>
<tr><td>重さ</td><td>やや重め。波の中で安定しやすい</td><td>軽い。取り回しが楽</td></tr>
<tr><td>浮力</td><td>標準</td><td>同じ体積でも浮きやすい</td></tr>
<tr><td>乗り味</td><td>しなやかで、水に吸い付くような感触</td><td>反応が速く、軽快。小波で走りやすい</td></tr>
<tr><td>強さ</td><td>凹みやすいが、長年の実績がある</td><td>凹みにくい傾向。ただし傷から水を吸うと注意が必要</td></tr>
<tr><td>修理</td><td>多くのショップで対応できる</td><td>エポキシ樹脂での修理が必要</td></tr>
</table>
<p class="note">※ 一般的な傾向です。実際の乗り味は、形・ガラスの巻き方・ストリンガーなどの組み合わせで変わります。</p>

<h2 id="choose">どちらを選ぶ？</h2>
<ul>
<li><b>PU がおすすめ</b>：しっとりした乗り味が好き、風の強い日やサイズのある波にも乗る、クラシックな仕上げ（ティントなど）にしたい。</li>
<li><b>EPS がおすすめ</b>：とにかく軽く、浮力が欲しい、小波で走らせたい、持ち運びを楽にしたい。</li>
</ul>
<p>EPS は浮力が出やすいため、同じ感覚で乗るなら PU より2〜3L少なめが目安と言われます。ボリュームの考え方は<a href="../../column/how-to-choose-surfboard/">サーフボードの選び方</a>をご覧ください。</p>

<h2 id="repair">修理のときは素材を伝えて</h2>
<p>PU と EPS では、修理に使う樹脂が異なります。修理を相談するときは、ボードの素材がわかれば一緒に伝えてください。わからなくても、お店で確認できます。詳しくは<a href="../../column/surfboard-repair/">サーフボード修理ガイド</a>へ。</p>
