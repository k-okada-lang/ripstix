<h2 id="wada">和田浦エリア（白渚から近い）</h2>
<h3>道の駅 和田浦 WA・O!（ワオ）</h3>
<p>白渚と同じ和田町にある、くじらがテーマの道の駅です。直売所では地元の採れたて野菜や、南房総ならではの海産物・銘菓を販売しています。食事処「和田浜」では、和田浦名産のくじら料理や、アジなどの地魚料理を味わえます。くじらの竜田揚げのような、ほかではなかなか食べられない一品もあります。</p>
<ul>
<li><b>住所</b>：千葉県南房総市和田町仁我浦243</li>
<li><b>営業時間</b>：直売所 9:00〜17:30、レストラン 10:00〜16:00（ラストオーダー15:30）</li>
<li><b>定休日</b>：無休</li>
<li><b>アクセス</b>：JR和田浦駅から徒歩約8分。駐車場は無料（乗用車115台）</li>
</ul>
<p>海岸までは歩いて3分ほど。サーフィンのあとにお昼を食べて、おみやげを買って帰るのにちょうどいい場所です。和田浦は昔ながらの漁師町の風景が残る町でもあります。</p>

<h2 id="chikura">千倉エリア</h2>
<h3>白間津（しらまづ）のお花畑</h3>
<p>千倉町白間津は、真冬でも霜が降りることがほとんどない温暖な地域で、切り花の露地栽培が盛んです。菜の花、金魚草、キンセンカ、ストックなどが育てられていて、<strong>1月上旬から3月中旬にかけて花摘み</strong>を楽しめます。太平洋を背に、海側へ花畑が続く景色は、冬の南房総ならではです。</p>
<ul>
<li><b>場所</b>：千葉県南房総市千倉町白間津</li>
<li><b>料金・営業時間</b>：花摘みは各花園によって異なります</li>
<li><b>問い合わせ</b>：南房総市観光協会 千倉観光案内所（0470-44-3581）</li>
<li><b>駐車場</b>：無料（乗用車30台）</li>
</ul>
<p>冬は北西の風で外房のポイントがオフショアになりやすい季節です。朝に波に乗って、昼から花摘み、という冬の過ごし方もおすすめです。</p>
<h3>高家神社（たかべじんじゃ）</h3>
<p>日本で唯一、料理の神様をまつる神社です。料理上達のお守りや、限定の高級しょうゆを買うことができます。料理好きの方へのおみやげ選びにもどうぞ。</p>

<h2 id="shirahama">白浜エリア（房総半島の最南端）</h2>
<h3>野島埼灯台</h3>
<p>房総半島の最南端に立つ灯台です。明治2年に建てられた、日本で最初の洋式灯台8基のひとつに数えられています。白い姿から「白鳥の灯台」とも呼ばれ、全国に16しかない「登れる灯台」のひとつです。らせん階段を上った展望台からは、房総半島と太平洋をぐるりと見渡せます。</p>
<ul>
<li><b>住所</b>：千葉県南房総市白浜町白浜630</li>
<li><b>参観料</b>：300円（中学生以上）</li>
<li><b>参観時間</b>：3〜9月は平日9:00〜16:30・土日祝8:30〜17:00、10〜2月は平日9:00〜16:00・土日祝8:30〜16:00（12:00〜13:00は休み）</li>
<li><b>アクセス</b>：富津館山道路 富浦ICから約30分</li>
</ul>
<p>半島の先端にあるため星空がきれいなことでも知られています。荒天のときや工事のときは休みになるので、出かける前に確認しましょう。</p>
<h3>道の駅 白浜野島崎</h3>
<p>千葉県でいちばん南にある道の駅です（営業時間 9:00〜16:00、年末年始休み）。野島埼灯台を見に行くときの休憩にどうぞ。</p>

<h2 id="tateyama">館山エリア</h2>
<h3>城山公園</h3>
<p>四季折々の花が咲く公園で、山頂からは館山の市内と海を一望できます。館山の南側には、北〜北東の風の日に候補になるサーフポイント平砂浦もあります。<a href="../../column/minamiboso-surfing/">南房総でサーフィンするなら</a>で、風向きとエリアの選び方を紹介しています。</p>

