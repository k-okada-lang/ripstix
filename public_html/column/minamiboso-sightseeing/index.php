<h2 id="area">南房総観光の回り方</h2>
<p>白渚のある和田町は、南房総市の東側、外房の海沿いにあります。ここから国道128号などで海沿いを南へ進むと千倉、さらに房総半島の先端の白浜、西へ回り込むと館山に出ます。海岸沿いに見どころが並んでいるので、「朝はサーフィン、昼から海沿いを南へドライブ」という回り方がしやすいエリアです。</p>
