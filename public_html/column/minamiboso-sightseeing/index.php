<h2 id="tips">サーファーの観光のコツ</h2>
<ul>
<li><b>朝いちばんに波をチェック</b>：風が弱い朝のうちに海に入り、風が上がる昼から観光に回すと、一日を無駄なく使えます。</li>
<li><b>波がない日の予備プランを持つ</b>：南房総は海岸の向きがいろいろなので、どこかで波に乗れる日が多いエリアです。それでも波がない日は、観光の日に切り替えましょう。</li>
<li><b>濡れたボードを車に置きっぱなしにしない</b>：夏場の車内は高温になり、ボードが傷む原因になります。<a href="../../column/surfboard-care/">サーフボードの保管とメンテナンス</a>もどうぞ。</li>
<li><b>泊まりで来るなら白渚へ</b>：SPLASH の2階は、全室から波が見える素泊まりの宿です。<a href="../../column/splash-shirasuka/">SPLASH（スプラッシュ）白渚</a>で紹介しています。</li>
</ul>
