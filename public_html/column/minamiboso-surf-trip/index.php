<h2 id="why">泊まりで行くと何がいいか</h2>
<ul>
<li><b>朝いちばんの波に乗れる</b>：風が弱く、波の形が整いやすい早朝に、移動の疲れなしで海に入れます。</li>
<li><b>2日分のチャンスがある</b>：初日の波が合わなくても、翌日の風やうねりの変化で良い波に当たることがあります。</li>
<li><b>観光と両立しやすい</b>：昼の風が上がる時間に観光へ回し、夕方にもう一度海へ、という組み立てができます。</li>
<li><b>運転が楽になる</b>：早朝出発や夜の帰り道を減らせるので、安全に楽しめます。</li>
</ul>

