<h2 id="flat">波がない日のプラン</h2>
<p>南房総は、東向きの外房側と、南〜南西向きの館山側で海岸の向きが違うため、風向きを見てポイントを変えれば、どこかで波に乗れる日が多いエリアです。風向きごとの選び方は<a href="../../column/minamiboso-surfing/">南房総でサーフィンするなら</a>にまとめています。</p>
<p>それでも波がない日は、思い切って観光の日にしましょう。</p>
<ul>
<li>白間津のお花畑で花摘み（1月上旬〜3月中旬）</li>
<li>日本で唯一、料理の神様をまつる高家神社</li>
<li>房総半島の最南端、登れる灯台の野島埼灯台</li>
<li>館山の城山公園から、市内と海を一望</li>
</ul>
<p>各スポットの住所や営業時間は<a href="../../column/minamiboso-sightseeing/">南房総観光ガイド</a>で紹介しています。小さい波でもよく走るボードがあれば、波がない日でも楽しめる時間が増えます。<a href="../../column/unique-surfboards/">ユニークなサーフボード図鑑</a>でグラベラーやフィッシュを紹介しています。</p>

