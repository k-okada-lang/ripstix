<h2 id="what">オリジナルサーフボードとは</h2>
<p>オリジナルサーフボードとは、お店に並んでいる既製品（ストックボード）ではなく、<strong>自分の体格・レベル・よく入る波・好きなデザインに合わせて作るサーフボード</strong>のことです。「カスタムボード」「オーダーメイドのボード」とも呼ばれます。</p>
<p>オリジナルにできる部分は、大きく分けて2つあります。</p>
<ul>
<li><b>形（シェイプ）</b>：長さ・幅・厚み・ボリューム、アウトライン（輪郭）、テール、ロッカー（反り）、フィンの配置など、乗り味を決める部分。</li>
<li><b>見た目（デザイン）</b>：カラー、ピンライン、ロゴの位置、ネームや文字など、世界に一つだけの見た目を決める部分。</li>
</ul>
<p>どちらか片方だけをオリジナルにすることもできますし、両方を自分仕様にすることもできます。</p>

<h2 id="ways">作り方は3つ：違いを比べる</h2>
<table class="tbl"><thead><tr><th>作り方</th><th>どんな方法</th><th>向いている人</th></tr></thead><tbody>
<tr><td>シェイパーにフルオーダー</td><td>シェイパーと相談しながら、形もデザインもゼロから決める</td><td>乗り味まで自分に合わせたい人、2本目以降の人</td></tr>
<tr><td>既存モデルをカスタム</td><td>ショップのモデルをベースに、サイズ・フィン・カラーなどを指定する</td><td>はじめてのオーダーで、失敗を減らしたい人</td></tr>
<tr><td>自作（ハンドシェイプ）</td><td>ブランクス（芯材）を自分で削り、樹脂で仕上げる</td><td>ものづくりそのものを楽しみたい人</td></tr>
</tbody></table>
<h3>シェイパーにフルオーダー</h3>
<p>もっとも自由度が高く、乗り味まで自分に合わせられる方法です。いま乗っているボードの感想や、よく入る波、こうなりたいというイメージをシェイパーに伝え、形に落とし込んでもらいます。シェイパーとのやりとりそのものが、ボードへの愛着につながります。既製品との違いは<a href="../../column/shaper-vs-stock/">カスタムボードと既製品の比較</a>で詳しく紹介しています。</p>
<h3>既存モデルをカスタム</h3>
<p>乗り味が確かめられているモデルをベースにするので、はじめてでも失敗が少ない方法です。長さやボリュームを体格に合わせて調整し、カラーやロゴで自分らしさを出します。「形はおまかせ、見た目は思いきり自分らしく」という頼み方もできます。</p>
<h3>自作（ハンドシェイプ）</h3>
<p>道具と作業場所、時間が必要で、思ったとおりに仕上げるには経験もいります。乗り味より「自分の手で作った」ことに価値を感じる方に向いています。ワークショップなど、プロに教わりながら作れる機会を利用するのも手です。</p>

<h2 id="decide">決めることリスト（この順番で決めると迷わない）</h2>
<ol class="steps">
<li><b>どこで、どんな波に乗りたいか</b>：よく入るポイントと、いちばん多い波のサイズ。ここがすべての出発点です。</li>
<li><b>サイズとボリューム</b>：身長・体重・レベル・サーフィンの頻度から、長さとボリューム（リッター）の目安を決めます。目安は<a href="../../column/how-to-choose-surfboard/">サーフボードの選び方</a>で紹介しています。</li>
<li><b>形のタイプ</b>：ショートボード、フィッシュ、ミッドレングスなど。迷ったら<a href="../../column/unique-surfboards/">ユニークなサーフボード図鑑</a>も参考に。</li>
<li><b>テールとフィン</b>：<a href="../../column/surfboard-tail-types/">テールの種類</a>と<a href="../../column/surfboard-fin-setup/">フィンのセッティング</a>で、ターンの軽さやスピードの出方が変わります。</li>
<li><b>素材</b>：PU か EPS か。重さ・浮力・乗り味・耐久性が違います（<a href="../../column/pu-vs-eps/">PU と EPS の違い</a>）。</li>
<li><b>デザイン</b>：カラーの入れ方（ティント、レジンワーク、スプレー）、ピンライン、ロゴの位置、ストリンガー。詳しくは<a href="../../column/one-of-a-kind-surfboard/">世界に一つだけのサーフボードのつくり方</a>へ。</li>
</ol>
<p class="note">乗り味に関わること（1〜5）を先に決め、見た目（6）は最後に決めるのがコツです。デザインから考え始めると、形が後回しになって「かっこいいけれど乗りにくい」ボードになりがちです。</p>

<h2 id="cost">費用はどう決まる？見積もりの考え方</h2>
<p>オリジナルサーフボードの価格は、おもに次の要素で決まります。</p>
<ul>
<li><b>長さとモデル</b>：長いボードほど材料と手間が増えます。</li>
<li><b>素材</b>：PU と EPS、ブランクスの種類で変わります。</li>
<li><b>カラーの手法</b>：クリア（色なし）がもっともシンプルで、ティントやレジンワーク、スプレーなど手間のかかる手法ほど上がります。</li>
<li><b>オプション</b>：ピンライン、ロゴ、フィンボックスの種類、グラス（ガラスクロス）の厚みなど。</li>
</ul>
<p>はじめに「予算はこれくらい」と伝えておくと、その範囲でできるいちばん良い仕様を提案してもらいやすくなります。見積もりをもらったら、どこにお金がかかっているのかを聞いてみましょう。優先したいところ（乗り味か、見た目か）がはっきりして、納得のいく一本になります。RIPSTIX では、仕様をうかがったうえで価格と納期をご案内しています。</p>

<h2 id="time">製作期間と、頼むタイミング</h2>
<p>オリジナルボードは、シェイプ、ラミネート（樹脂とガラスクロスでコーティング）、研ぎ、仕上げと、いくつもの工程を経て完成します。製作期間は、時期や仕様、カラーの有無によって変わります。</p>
<p>サーフィンをする人が増える春〜夏の前は、オーダーが集中しやすい時期です。「この夏に乗りたい」「台風シーズンに間に合わせたい」という場合は、乗りたい時期から逆算して、早めに相談するのがおすすめです。</p>

<h2 id="tips">失敗しないための5つのコツ</h2>
<ol class="steps">
<li><b>いま乗っているボードの寸法を測っておく</b>：長さ・幅・厚み・ボリュームがわかると、シェイパーとの話が一気に具体的になります。</li>
<li><b>「好き」と「不満」を言葉にする</b>：「パドルは楽だけどターンが重い」など、いまのボードの感想が、次の一本のヒントになります。</li>
<li><b>見栄を張らない</b>：上級者向けの薄いボードは、レベルに合わないと波に乗れる本数が減ってしまいます。今の自分に合うボリュームを選ぶのが上達への近道です。</li>
<li><b>デザインは見本で伝える</b>：好きなボードの写真や色見本があると、イメージのずれを防げます。</li>
<li><b>完成形を目で確かめる</b>：3D シミュレーターなどで、色やロゴの配置を事前に確認しておくと安心です。</li>
</ol>
