<h2 id="wave">白渚の波の特徴</h2>
<p>白渚は、砂に覆われたリーフと岩の上で割れる、レフトとライトがあるポイントです。海外のサーフガイド「Surfing in Japan」でも、このエリアで<strong>最もコンスタントで形の良い波</strong>のひとつとして紹介されています。サイズが上がっても形を保ちやすいのが特徴です。</p>
<ul>
<li><b>ボトム</b>：砂の下にリーフや岩がある場所があります。</li>
<li><b>ベストな風</b>：北西（オフショア）。</li>
<li><b>混雑</b>：夏の小さい日は混み合うことがあります。サイズが上がると人は減る傾向です。</li>
</ul>
<p class="note">※ 波の特徴は Surfing in Japan の和田エリア解説を参考にしています。海の状況は日々変わります。入る前に必ず自分の目で確認し、地元のサーファーのルールに従ってください。</p>

<h2 id="manner">白渚で気持ちよく入るために</h2>
<ul>
<li>ピークの優先順位（前乗りしない）を守る</li>
<li>出入りのときは、岩の場所を確認してから</li>
<li>駐車やゴミ、着替えのマナーを守り、地域の人に迷惑をかけない</li>
<li>はじめての日は、ショップで波の様子や注意点を聞いてから入る</li>
</ul>

<h2 id="board">白渚に合うボード</h2>
<p>ふだんの腰〜胸サイズなら、浮力のあるショートボードやフィッシュ、ミッドレングスが楽しめます。サイズのある日は、ホールドの効くラウンドピンやスカッシュのショートボードが活躍します。RIPSTIX のボードは、この白渚の波でテストしながら削られています。ボード選びは<a href="../../column/how-to-choose-surfboard/">サーフボードの選び方</a>もどうぞ。</p>

