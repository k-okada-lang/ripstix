<h2 id="after">海から上がったら</h2>
<ol>
<li><b>真水で流す</b>：塩と砂を落とします。特にフィンの付け根やリーシュカップのまわり。</li>
<li><b>日陰で乾かす</b>：直射日光の下に置きっぱなしにしないこと。</li>
<li><b>傷をチェック</b>：小さな穴やひびがないか確認します。見つけたら<a href="../../column/surfboard-repair/">修理ガイド</a>を参考に、早めに対処を。</li>
</ol>

<h2 id="heat">熱と紫外線に注意</h2>
<p>サーフボードの大敵は、熱と紫外線です。真夏の車内や直射日光の下に長時間置くと、中のフォームの空気がふくらみ、表面のガラスが剥がれる<strong>デラミ</strong>の原因になります。また紫外線は、フォームやカラーの変色（黄ばみ）を早めます。</p>
<ul>
<li>車に置くときは、日よけやボードケースを使い、短時間に</li>
<li>浜でもデッキを上にして日なたに置かず、日陰やタオルの下へ</li>
<li>家では、直射日光の当たらない、風通しの良い場所に</li>
</ul>

<h2 id="store">保管のコツ</h2>
<ul>
<li>ボードケースに入れて保管する（ほこり・小さな衝撃・紫外線から守る）</li>
<li>壁に立てかけるときは、テール側を下にして、レールが傷つかないよう柔らかいものを敷く</li>
<li>ラックに置くときは、レールで支えるタイプか、デッキを下にして平らに</li>
<li>長く乗らないときも、ときどき状態を確認する</li>
</ul>

<h2 id="wax">ワックスの塗り替え</h2>
<p>ワックスは、汚れや砂を含むと滑りやすくなります。季節（水温）に合ったワックスを使い、汚れてきたら古いワックスを落として塗り直しましょう。ワックスを落としたときに、デッキの小さなひびや凹みに気づくこともあります。</p>

<h2 id="fin">フィンとリーシュも忘れずに</h2>
<p>フィンは付けっぱなしにせず、ときどき外してネジや付け根を点検しましょう。リーシュコードは、ひび割れやほつれがあれば早めに交換を。切れると自分にも周りのサーファーにも危険です。</p>
